document.querySelector("#editor-save-button").addEventListener("click", async (event) => {
  if (!editor.file) return;
  if (!editor.layers.length && !editor.deletedPages.size) {
    showStatus(localize(
      "أضف طبقة أو احذف صفحة واحدة على الأقل قبل الحفظ.",
      "Add a layer or delete at least one page before saving.",
    ), true);
    return;
  }
  const button = event.currentTarget;
  const data = new FormData();
  data.set("file", editor.file);
  data.set("edits", JSON.stringify(editor.layers.map(({ id, ...layer }) => layer)));
  data.set("deleted_pages", JSON.stringify([...editor.deletedPages]));
  data.set("output_name", document.querySelector("#editor-output-name").value || "layered.pdf");
  if (editorFont.files[0]) data.set("font", editorFont.files[0]);
  button.disabled = true;
  showStatus(localize("جارٍ حفظ الطبقات فوق نسخة جديدة من الملف…", "Saving the layers to a new copy of the file…"));
  try {
    const response = await fetch("/api/layer-edit", { method: "POST", body: data });
    if (!response.ok) {
      let message = localize("تعذّر حفظ التعديلات.", "The changes could not be saved.");
      try { message = serverMessageOrFallback((await response.json()).detail, message); } catch (_) { /* Not JSON. */ }
      throw new Error(message);
    }
    downloadBlob(await response.blob(), responseFilename(response, "layered.pdf"));
    const serverMessage = decodeURIComponent(response.headers.get("x-pdf-control-message") || "");
    showStatus(serverMessage && activeLanguage === "ar"
      ? serverMessage
      : localize("تم حفظ النسخة الجديدة.", "The new copy was saved."));
  } catch (error) {
    showStatus(error.message, true);
  } finally {
    button.disabled = false;
  }
});

