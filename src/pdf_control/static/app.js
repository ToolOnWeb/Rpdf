const previewRetryDelays = [350, 800, 1500];

function wait(milliseconds) {
  return new Promise((resolve) => window.setTimeout(resolve, milliseconds));
}

async function fetchPreviewWithRetry(url, options) {
  let response;
  for (let attempt = 0; attempt <= previewRetryDelays.length; attempt += 1) {
    response = await fetch(url, options);
    if (![429, 503].includes(response.status) || attempt === previewRetryDelays.length) {
      return response;
    }
    const retryAfter = Number(response.headers.get("retry-after"));
    const delay = Number.isFinite(retryAfter) && retryAfter > 0
      ? Math.min(retryAfter * 1000, 5000)
      : previewRetryDelays[attempt];
    await wait(delay);
  }
  return response;
}

function imageBlobAsDataUrl(blob) {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.addEventListener("load", () => resolve(reader.result), { once: true });
    reader.addEventListener("error", () => reject(new Error(localize(
      "تعذّرت قراءة صورة المعاينة.",
      "The preview image could not be read.",
    ))), { once: true });
    reader.readAsDataURL(blob);
  });
}

function releaseObjectUrl(url) {
  if (typeof url === "string" && url.startsWith("blob:")) URL.revokeObjectURL(url);
}

function clearPreview() {
  if (previewState.request) previewState.request.abort();
  if (previewState.session) {
    fetch(`/api/preview-session/${encodeURIComponent(previewState.session)}`, {
      method: "DELETE", keepalive: true,
    }).catch(() => { /* Expired sessions are cleaned up by the server. */ });
  }
  previewState.request = null;
  previewState.images.clear();
  previewState.pendingImages.clear();
  previewState.file = null;
  previewState.session = null;
  previewState.page = 1;
  previewState.totalPages = 1;
  previewImage.removeAttribute("src");
  previewImage.hidden = true;
  previewViewer.hidden = true;
}

function updatePreviewControls(loading = false) {
  document.querySelector("#preview-page").textContent = previewState.page;
  document.querySelector("#preview-pages").textContent = previewState.totalPages;
  previewPrevious.disabled = loading || previewState.page <= 1;
  previewNext.disabled = loading || previewState.page >= previewState.totalPages;
}

async function fetchPreviewSessionPage(page) {
  if (previewState.images.has(page)) return previewState.images.get(page);
  if (previewState.pendingImages.has(page)) return previewState.pendingImages.get(page);
  let session = previewState.session;
  if (!session) return null;

  const pending = (async () => {
    const data = new FormData();
    data.set("session", session);
    data.set("page", String(page));
    data.set("dpi", "96");
    let response = await fetchPreviewWithRetry("/api/preview-page", { method: "POST", body: data });
    if (response.status === 404 && previewState.session === session) {
      const renewalData = new FormData();
      renewalData.set("file", previewState.file);
      renewalData.set("dpi", "96");
      const renewal = await fetchPreviewWithRetry("/api/preview-session", { method: "POST", body: renewalData });
      if (renewal.ok) {
        session = renewal.headers.get("x-preview-session");
        if (!session) throw new Error(localize(
          "تعذّر تجديد جلسة المعاينة.",
          "The preview session could not be renewed.",
        ));
        previewState.session = session;
        previewState.totalPages = Number(renewal.headers.get("x-page-count")) || previewState.totalPages;
        const firstPageUrl = await imageBlobAsDataUrl(await renewal.blob());
        previewState.images.set(1, firstPageUrl);
        if (page === 1) return firstPageUrl;
        const retryData = new FormData();
        retryData.set("session", session);
        retryData.set("page", String(page));
        retryData.set("dpi", "96");
        response = await fetchPreviewWithRetry("/api/preview-page", { method: "POST", body: retryData });
      } else {
        response = renewal;
      }
    }
    if (!response.ok) {
      let message = localize("تعذّرت معاينة الملف.", "The file could not be previewed.");
      try { message = serverMessageOrFallback((await response.json()).detail, message); } catch (_) { /* Not JSON. */ }
      throw new Error(message);
    }
    const imageUrl = await imageBlobAsDataUrl(await response.blob());
    if (previewState.session === session) {
      previewState.totalPages = Number(response.headers.get("x-page-count")) || previewState.totalPages;
      previewState.images.set(page, imageUrl);
    }
    return imageUrl;
  })();
  previewState.pendingImages.set(page, pending);
  try {
    return await pending;
  } finally {
    if (previewState.pendingImages.get(page) === pending) previewState.pendingImages.delete(page);
  }
}

function prefetchPreviewPage(page) {
  if (!previewState.session || page > previewState.totalPages || previewState.images.has(page)) return;
  fetchPreviewSessionPage(page).catch(() => { /* A foreground request will report any error. */ });
}

async function loadPreviewPage(page) {
  if (!previewState.file || page < 1 || page > previewState.totalPages) return;
  if (previewState.request) previewState.request.abort();
  const request = new AbortController();
  previewState.request = request;
  previewState.page = page;
  previewViewer.hidden = false;
  previewLoading.hidden = false;
  updatePreviewControls(true);

  try {
    let imageUrl = previewState.images.get(page);
    if (!imageUrl) {
      if (previewState.session) {
        imageUrl = await fetchPreviewSessionPage(page);
      } else {
        const data = new FormData();
        data.set("file", previewState.file);
        data.set("dpi", "96");
        const response = await fetchPreviewWithRetry("/api/preview-session", {
          method: "POST", body: data, signal: request.signal,
        });
        if (!response.ok) {
          let message = localize("تعذّرت معاينة الملف.", "The file could not be previewed.");
          try { message = serverMessageOrFallback((await response.json()).detail, message); } catch (_) { /* Not JSON. */ }
          throw new Error(message);
        }
        previewState.totalPages = Number(response.headers.get("x-page-count")) || 1;
        previewState.session = response.headers.get("x-preview-session");
        if (!previewState.session) throw new Error(localize(
          "تعذّر بدء جلسة المعاينة.",
          "The preview session could not be started.",
        ));
        imageUrl = await imageBlobAsDataUrl(await response.blob());
        previewState.images.set(page, imageUrl);
      }
    }
    if (previewState.request !== request) return;
    previewImage.src = imageUrl;
    previewImage.hidden = false;
    try {
      await previewImage.decode();
    } catch (_) {
      throw new Error(localize("تعذّر عرض صورة المعاينة.", "The preview image could not be displayed."));
    }
    showStatus(localize(
      `تم عرض الصفحة ${page} من ${previewState.totalPages}.`,
      `Showing page ${page} of ${previewState.totalPages}.`,
    ));
    prefetchPreviewPage(page + 1);
  } catch (error) {
    if (error.name !== "AbortError") showStatus(error.message, true);
  } finally {
    if (previewState.request === request) {
      previewState.request = null;
      previewLoading.hidden = true;
      updatePreviewControls();
    }
  }
}

