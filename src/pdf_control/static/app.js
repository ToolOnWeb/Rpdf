function editorPoint(event) {
  const bounds = editorOverlay.getBoundingClientRect();
  const scale = editorScale();
  return {
    x: Math.max(0, Math.min(editor.width, (event.clientX - bounds.left) / scale)),
    y: Math.max(0, Math.min(editor.height, (event.clientY - bounds.top) / scale)),
  };
}

async function loadEditorPage(page = editor.page) {
  if (!editor.file || editor.loadingPage) return false;
  editor.loadingPage = true;
  editorLoading.hidden = false;
  updateEditorActions();
  const data = new FormData();
  let endpoint = "/api/preview-page";
  const usingExistingSession = Boolean(editor.previewSession);
  if (usingExistingSession) {
    data.set("session", editor.previewSession);
    data.set("page", String(page));
  } else {
    endpoint = "/api/preview-session";
    data.set("file", editor.file);
  }
  data.set("dpi", "120");
  try {
    let renewedSession = false;
    let response = await fetchPreviewWithRetry(endpoint, { method: "POST", body: data });
    if (response.status === 404 && usingExistingSession) {
      const renewalData = new FormData();
      renewalData.set("file", editor.file);
      renewalData.set("dpi", "120");
      response = await fetchPreviewWithRetry("/api/preview-session", { method: "POST", body: renewalData });
      if (response.ok) {
        editor.previewSession = response.headers.get("x-preview-session");
        if (!editor.previewSession) throw new Error(localize(
          "تعذّر تجديد جلسة المعاينة.",
          "The preview session could not be renewed.",
        ));
        renewedSession = true;
        if (page !== 1) {
          const pageData = new FormData();
          pageData.set("session", editor.previewSession);
          pageData.set("page", String(page));
          pageData.set("dpi", "120");
          response = await fetchPreviewWithRetry("/api/preview-page", { method: "POST", body: pageData });
        }
      }
    }
    if (!response.ok) {
      let message = localize("تعذّرت معاينة الملف.", "The file could not be previewed.");
      try { message = serverMessageOrFallback((await response.json()).detail, message); } catch (_) { /* Not JSON. */ }
      throw new Error(message);
    }
    const blob = await response.blob();
    releaseObjectUrl(editor.imageUrl);
    editor.imageUrl = await imageBlobAsDataUrl(blob);
    editor.page = page;
    editor.totalPages = Number(response.headers.get("x-page-count"));
    if (!editor.previewSession) {
      editor.previewSession = response.headers.get("x-preview-session");
      if (!editor.previewSession) throw new Error(localize(
        "تعذّر بدء جلسة المعاينة.",
        "The preview session could not be started.",
      ));
    }
    editor.width = Number(response.headers.get("x-page-width"));
    editor.height = Number(response.headers.get("x-page-height"));
    editorImage.src = editor.imageUrl;
    try {
      await editorImage.decode();
    } catch (_) {
      throw new Error(localize("تعذّر عرض صورة الصفحة.", "The page image could not be displayed."));
    }
    clearStatus();
    applyEditorZoom();
    if (renewedSession) showStatus(localize(
      "تم تجديد جلسة المعاينة ومتابعة العمل.",
      "The preview session was renewed and editing can continue.",
    ));
    return true;
  } catch (error) {
    showStatus(error.message, true);
    return false;
  } finally {
    editor.loadingPage = false;
    editorLoading.hidden = true;
    updateEditorActions();
  }
}

