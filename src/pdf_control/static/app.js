const originalText = new WeakMap();
const originalAttributes = new WeakMap();

function localize(arabic, english) {
  return activeLanguage === "en" ? english : arabic;
}

function translateStaticContent() {
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    if (!originalText.has(node)) originalText.set(node, node.nodeValue);
    const source = originalText.get(node);
    const phrase = source.trim();
    const translated = activeLanguage === "en" ? englishTranslations[phrase] : phrase;
    if (!translated || translated === phrase) {
      node.nodeValue = source;
      continue;
    }
    node.nodeValue = source.replace(phrase, translated);
  }

  document.querySelectorAll("[aria-label], [title], [alt], meta[content]").forEach((element) => {
    const saved = originalAttributes.get(element) || {};
    ["aria-label", "title", "alt", "content"].forEach((attribute) => {
      if (!element.hasAttribute(attribute)) return;
      if (!(attribute in saved)) saved[attribute] = element.getAttribute(attribute);
      const source = saved[attribute];
      element.setAttribute(attribute, activeLanguage === "en" ? (englishTranslations[source] || source) : source);
    });
    originalAttributes.set(element, saved);
  });

  const localizedValues = { all: { ar: "الكل", en: "all" }, reviewed: { ar: "تمت المراجعة", en: "Reviewed" } };
  document.querySelectorAll("[data-i18n-value]").forEach((input) => {
    const values = localizedValues[input.dataset.i18nValue];
    if (!values) return;
    const previousLanguage = activeLanguage === "en" ? "ar" : "en";
    if (input.value === values[previousLanguage] || input.value === values[activeLanguage]) {
      input.value = values[activeLanguage];
    }
  });
}

