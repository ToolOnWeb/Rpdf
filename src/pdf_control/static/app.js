async function goToEditorPage() {
  const input = document.querySelector("#editor-page-input");
  const page = Number(input.value);
  if (!Number.isInteger(page) || page < 1 || page > editor.totalPages) {
    showStatus(localize(
      `أدخل رقم صفحة من 1 إلى ${editor.totalPages}.`,
      `Enter a page number from 1 to ${editor.totalPages}.`,
    ), true);
    input.focus();
    input.select();
    return;
  }
  if (editor.deletedPages.has(page)) {
    showStatus(localize(
      `الصفحة ${page} محددة للحذف. تراجع عن الحذف أولًا للانتقال إليها.`,
      `Page ${page} is marked for deletion. Undo the deletion before opening it.`,
    ), true);
    input.focus();
    input.select();
    return;
  }
  await loadEditorPage(page);
}
